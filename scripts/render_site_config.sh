#!/bin/bash
#######################################
# Render a per-site config from a profile
#
# Usage:
#   render_site_config.sh <site_id> <project_dir> [profile] [options]
#
# Options:
#   --alert-email EMAIL
#   --wechat-webhook URL
#   --dingtalk-webhook URL
#   --auto-restore true|false
#   --output-dir DIR
#   --critical-file PATH   (repeatable)
#   --whitelist-dir PATH   (repeatable)
#   --no-profile-defaults
#######################################

set -euo pipefail

SCRIPT_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROFILES_DIR="${PROFILES_DIR:-$SCRIPT_HOME/profiles}"
OUTPUT_DIR="/etc/webshell-monitor/sites"
LOG_ROOT="/var/log/webshell"
QUARANTINE_ROOT="/var/quarantine"
BACKUP_ROOT="/var/webshell_backup"

PROFILE="thinkphp"
ALERT_EMAIL=""
WECHAT_WEBHOOK=""
DINGTALK_WEBHOOK=""
AUTO_RESTORE="true"
USE_PROFILE_DEFAULTS=1
EXTRA_CRITICAL=()
EXTRA_WHITELIST=()
POSITIONAL=()

usage() {
    cat <<'EOF'
用法: render_site_config.sh <site_id> <project_dir> [profile] [options]

Options:
  --alert-email EMAIL
  --wechat-webhook URL
  --dingtalk-webhook URL
  --auto-restore true|false
  --output-dir DIR
  --critical-file PATH
  --whitelist-dir PATH
  --no-profile-defaults
EOF
    exit 1
}

validate_site_id() {
    if [[ ! "$1" =~ ^[a-zA-Z0-9][a-zA-Z0-9_-]*$ ]]; then
        echo "错误: site_id 仅允许字母数字、下划线、连字符，且不能以符号开头: $1" >&2
        exit 1
    fi
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --alert-email) ALERT_EMAIL="$2"; shift 2 ;;
        --wechat-webhook) WECHAT_WEBHOOK="$2"; shift 2 ;;
        --dingtalk-webhook) DINGTALK_WEBHOOK="$2"; shift 2 ;;
        --auto-restore) AUTO_RESTORE="$2"; shift 2 ;;
        --output-dir) OUTPUT_DIR="$2"; shift 2 ;;
        --critical-file) EXTRA_CRITICAL+=("$2"); shift 2 ;;
        --whitelist-dir) EXTRA_WHITELIST+=("$2"); shift 2 ;;
        --no-profile-defaults) USE_PROFILE_DEFAULTS=0; shift ;;
        -h|--help) usage ;;
        --*) echo "未知选项: $1" >&2; usage ;;
        *) POSITIONAL+=("$1"); shift ;;
    esac
done

if [ "${#POSITIONAL[@]}" -lt 2 ]; then
    usage
fi

SITE_ID="${POSITIONAL[0]}"
PROJECT_DIR="${POSITIONAL[1]}"
if [ "${#POSITIONAL[@]}" -ge 3 ]; then
    PROFILE="${POSITIONAL[2]}"
fi

validate_site_id "$SITE_ID"

if [ -d "$PROJECT_DIR" ]; then
    PROJECT_DIR="$(cd "$PROJECT_DIR" && pwd)"
else
    echo "错误: 项目目录不存在: $PROJECT_DIR" >&2
    exit 1
fi

PROFILE_FILE="$PROFILES_DIR/${PROFILE}.conf"
if [ ! -f "$PROFILE_FILE" ]; then
    echo "错误: 找不到 profile: $PROFILE_FILE" >&2
    exit 1
fi

# shellcheck source=/dev/null
source "$PROFILE_FILE"

mkdir -p "$OUTPUT_DIR"
mkdir -p "$LOG_ROOT" 2>/dev/null || true
mkdir -p "$QUARANTINE_ROOT/$SITE_ID" 2>/dev/null || true
mkdir -p "$BACKUP_ROOT/$SITE_ID" 2>/dev/null || true

CONF_FILE="$OUTPUT_DIR/${SITE_ID}.conf"
CRITICAL_FILE="$OUTPUT_DIR/${SITE_ID}.critical"
WHITELIST_FILE="$OUTPUT_DIR/${SITE_ID}.whitelist"

: > "$CRITICAL_FILE"
: > "$WHITELIST_FILE"

abs_path() {
    local p="$1"
    if [[ "$p" = /* ]]; then
        echo "$p"
    else
        echo "$PROJECT_DIR/$p"
    fi
}

if [ "$USE_PROFILE_DEFAULTS" -eq 1 ]; then
    for rel in "${CRITICAL_REL_PATHS[@]}"; do
        abs_path "$rel" >> "$CRITICAL_FILE"
    done
    for rel in "${WHITELIST_REL_DIRS[@]}"; do
        abs_path "$rel" >> "$WHITELIST_FILE"
    done
fi

for p in "${EXTRA_CRITICAL[@]:-}"; do
    [ -n "${p:-}" ] && abs_path "$p" >> "$CRITICAL_FILE"
done
for p in "${EXTRA_WHITELIST[@]:-}"; do
    [ -n "${p:-}" ] && abs_path "$p" >> "$WHITELIST_FILE"
done

awk 'NF && !seen[$0]++' "$CRITICAL_FILE" > "${CRITICAL_FILE}.tmp" && mv "${CRITICAL_FILE}.tmp" "$CRITICAL_FILE"
awk 'NF && !seen[$0]++' "$WHITELIST_FILE" > "${WHITELIST_FILE}.tmp" && mv "${WHITELIST_FILE}.tmp" "$WHITELIST_FILE"

RULES_DIR="$SCRIPT_HOME/rules"
if [ -d /opt/webshell_monitor/rules ]; then
    RULES_DIR="/opt/webshell_monitor/rules"
fi

cat > "$CONF_FILE" << EOF
# Auto-generated by render_site_config.sh — do not edit by hand if using GUI
SITE_ID="$SITE_ID"
PROJECT_DIR="$PROJECT_DIR"
PROFILE="$PROFILE"
LOG_FILE="$LOG_ROOT/${SITE_ID}.log"
QUARANTINE_DIR="$QUARANTINE_ROOT/$SITE_ID"
BACKUP_DIR="$BACKUP_ROOT/$SITE_ID"
AUTO_RESTORE="$AUTO_RESTORE"
ALERT_EMAIL="$ALERT_EMAIL"
WECHAT_WEBHOOK="$WECHAT_WEBHOOK"
DINGTALK_WEBHOOK="$DINGTALK_WEBHOOK"
DANGEROUS_EXTENSIONS="${DANGEROUS_EXTENSIONS}"
INOTIFY_EXCLUDE="${INOTIFY_EXCLUDE}"
CRITICAL_FILES_FILE="$CRITICAL_FILE"
WHITELIST_DIRS_FILE="$WHITELIST_FILE"
PHP_RULES_FILE="$RULES_DIR/php_webshell.rules"
HTML_RULES_FILE="$RULES_DIR/html_malware.rules"
EOF

chmod 640 "$CONF_FILE" "$CRITICAL_FILE" "$WHITELIST_FILE" 2>/dev/null || true
echo "已生成站点配置: $CONF_FILE"
echo "  关键文件列表: $CRITICAL_FILE ($(wc -l < "$CRITICAL_FILE" | tr -d ' ') 项)"
echo "  白名单目录: $WHITELIST_FILE ($(wc -l < "$WHITELIST_FILE" | tr -d ' ') 项)"
